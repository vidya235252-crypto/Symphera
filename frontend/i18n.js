let currentLang = 'en';

// Short helper: t('loading') returns the string in the current language
function t(key) {
  return I18N[currentLang][key];
}

// Swaps every marked element on the page to the chosen language
function applyLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = I18N[lang][el.dataset.i18n];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = I18N[lang][el.dataset.i18nPlaceholder];
  });
  document.querySelectorAll('.langs button').forEach(btn => {
    btn.setAttribute('aria-pressed', btn.dataset.lang === lang);
  });
}

applyLanguage('en');